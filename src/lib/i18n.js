export const DICTS = { en, fr }
export const LANGS = [
  { id: 'en', label: 'English', short: 'EN' },
  { id: 'fr', label: 'Français', short: 'FR' },
]

const get = (obj, path) => path.split('.').reduce((o, k) => (o == null ? o : o[k]), obj)

/** Translate outside React (toasts fired from event handlers, etc.). */
export function translate(lang, key, vars) {
  let v = get(DICTS[lang], key) ?? get(en, key) ?? key
  if (typeof v === 'string' && vars) v = v.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? `{${k}}`)
  return v
}

export const tNow = (key, vars) => translate(useExperience.getState().lang, key, vars)

/** React hook: returns `t(key, vars)` bound to the current language. */
export function useT() {
  const lang = useExperience((s) => s.lang)
  return useCallback((key, vars) => translate(lang, key, vars), [lang])
}
